/**
 * The accounting screens.
 *
 * Registered under `ledger` rather than `accounting`, because the shared
 * catalogue already owns `accounting` — the vocabulary every screen borrows
 * (debit, credit, trial balance, the voided-entry sentence). Screen merging is
 * one level deep and replaces wholesale, so registering this under the same
 * key would delete that vocabulary for everyone. Same reason `permissions`
 * registers as `explainer`.
 *
 * Two rules run through the copy here:
 *
 *   - A refusal says what the software will not do *and* what to do instead.
 *     "Unbalanced" is not a message; the exact difference is.
 *   - Nothing implies a calculation the system does not perform. There is no
 *     rate lookup, previews post nothing, and the balance sheet is never
 *     plugged. The copy has to be as honest as the ledger.
 */
